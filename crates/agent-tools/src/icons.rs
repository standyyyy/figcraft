/// The icon called `name`, or `None`.
///
/// A name may carry the catalog's `icon/` prefix or not: a model reading the icons file sees
/// `icon/add`, one reading a design sees `add`.
pub fn find(name: &str) -> Option<IconPath> {
    let wanted = name.strip_prefix("icon/").unwrap_or(name);
    ICONS.iter().copied().find(|(n, ..)| *n == wanted)
}

/// Every icon name, for a caller that lists them.
pub fn names() -> impl Iterator<Item = &'static str> {
    ICONS.iter().map(|(n, ..)| *n)
}

